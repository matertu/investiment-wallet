CREATE TYPE classe_ativo AS ENUM ('ACAO', 'FII', 'ETF', 'RENDA_FIXA');
CREATE TYPE indexador_rf AS ENUM ('CDI', 'SELIC', 'IPCA', 'PREFIXADO');
CREATE TYPE tipo_operacao AS ENUM ('APORTE', 'RESGATE');

-- 1. Supertipo: Cadastro único de qualquer ativo (nunca duplica código)
CREATE TABLE ativos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(30) UNIQUE NOT NULL, -- Ex: 'BBAS3', 'BBDC4', 'RESERVA_CDI'
  nome VARCHAR(100) NOT NULL,
  classe classe_ativo NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Subtipo (1:1): Atributos exclusivos de Renda Fixa (evita NULLs em ações)
CREATE TABLE detalhes_renda_fixa (
  ativo_id BIGINT PRIMARY KEY REFERENCES ativos(id) ON DELETE CASCADE,
  indexador indexador_rf NOT NULL,
  taxa_percentual NUMERIC(6, 2) NOT NULL CHECK (taxa_percentual >= 0), -- Ex: 120.00
  valor_atual NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (valor_atual >= 0),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. Tabela Única de Movimentações (Sessão de Aportes)
CREATE TABLE aportes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ativo_id BIGINT NOT NULL REFERENCES ativos(id) ON DELETE RESTRICT,
  tipo tipo_operacao NOT NULL DEFAULT 'APORTE',
  quantidade NUMERIC(14, 6) NOT NULL CHECK (quantidade > 0),
  valor_unitario NUMERIC(12, 4) NOT NULL CHECK (valor_unitario > 0),
  data_aporte DATE NOT NULL DEFAULT CURRENT_DATE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
